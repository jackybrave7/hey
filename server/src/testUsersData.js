// Главная функция — генерирует массив объектов для INSERT.
// count — сколько пользователей (обычно 100).
function generateTestUsers(count = 100) {
  const rng = mulberry32(42); // фиксированный seed → одинаковые юзера каждый раз
  const out = [];
  for (let i = 0; i < count; i++) {
    const useRu      = rng() < 0.65;
    const useFemale  = rng() < 0.5;
    const firstNames = useRu
      ? (useFemale ? FEMALE_NAMES_RU : MALE_NAMES_RU)
      : (useFemale ? FEMALE_NAMES_EN : MALE_NAMES_EN);
    const surnames = useRu ? SURNAMES_RU : SURNAMES_EN;
    const firstName = pick(firstNames, rng);
    const surname   = pick(surnames,   rng);
    // Имя в HEY: «Фамилия Имя» по-русски / «First Last» иностранцам, +
    // обязательный суффикс «тестовый» (для лёгкого визуального отличия и
    // защиты от случайного сохранения как реального юзера).
    const baseName = useRu ? `${firstName} ${surname}` : `${firstName} ${surname}`;
    const displayName = `${baseName} (тестовый)`;
    const theme = THEMES[i % THEMES.length];
    const bio = pick(theme.bioTemplates, rng);
    const moments = [];
    // 1-2 момента на юзера
    const mCount = 1 + Math.floor(rng() * 2);
    for (let k = 0; k < mCount; k++) {
      moments.push(pick(MOMENT_TEMPLATES, rng));
    }
    out.push({
      // ID детерминированный — для возможности безопасной идемпотентной чистки
      id: `test-user-${String(i).padStart(3, '0')}`,
      name: displayName,
      avatar: avatarForIndex(i, useFemale ? 'female' : 'male'),
      bio,
      headline: theme.profession,
      // Сразу делаем Super для половины — для тестирования отображения badge'ов
      is_super: rng() < 0.4 ? 1 : 0,
      moments,
    });
  }
  return out;
}

