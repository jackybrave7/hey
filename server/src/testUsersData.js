// Аватары: randomuser.me даёт стабильные URL на 100 мужских + 100 женских
// портретов, 0..99 каждого пола. Реальные лица.
function avatarForIndex(idx, gender) {
  const n = idx % 100;
  const g = gender === 'female' ? 'women' : 'men';
  return `https://randomuser.me/api/portraits/${g}/${n}.jpg`;
}

// Простой PRNG чтобы детерминированно «перемешать»
function mulberry32(seed) {
  return function() {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t ^= t + Math.imul(t ^ (t >>> 7), 61 | t);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function pick(arr, rng) { return arr[Math.floor(rng() * arr.length)]; }

